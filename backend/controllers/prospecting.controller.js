const db = require("../models");
const { Op } = require("sequelize");
const { sendErrorResponse } = require("../utility/sendErrorResponse");
const {
  ensureProspectingModuleForOrg,
  getEntitlementState,
  writeAudit,
} = require("../utility/prospectingAuthorization");

const clean = (value) => String(value || "").trim();
const asArray = (value) => (Array.isArray(value) ? value : []);

const buildTestProspects = ({ org_id, user_id, requestId, criteria = {}, providers = [] }) => {
  const industry = clean(criteria.industry) || "CRM Services";
  const region = clean(criteria.region) || "India";
  const provider = providers[0] || "phase2-test-provider";
  return [1, 2, 3].map((index) => ({
    org_id,
    requestId,
    companyName: `TEST DATA - ${industry} Prospect ${index}`,
    contactName: `TEST DATA - Decision Maker ${index}`,
    designation: index === 1 ? "Founder" : index === 2 ? "Sales Head" : "Operations Head",
    email: `test.prospect${index}@example.invalid`,
    mobile: `90000000${index}${index}`,
    website: `https://test-prospect-${index}.example.invalid`,
    industry,
    sourceProvider: provider,
    status: "review",
    verificationStatus: "verified",
    score: 70 + index * 6,
    scoreBreakdown: {
      icpFit: 25 + index,
      contactability: 20,
      intent: 15 + index,
      freshness: 10,
    },
    evidenceSummary: `TEST DATA - Matched ${industry} in ${region}; generated by Phase 2 mock provider only.`,
    createdBy: user_id,
  }));
};

const writeUsage = async ({ org_id, user_id, requestId, entryType, quantity, reason }) =>
  db.prospectingUsageLedger.create({
    org_id,
    user_id,
    requestId,
    entryType,
    quantity,
    direction: "debit",
    reason,
    idempotencyKey: `${entryType}:${requestId}:${reason}`,
  });

exports.getSummary = async (req, res) => {
  try {
    await ensureProspectingModuleForOrg(req.user.org_id);
    const state = await getEntitlementState(req.user.org_id);
    const settings = await db.prospectingOrgSetting.findOne({ where: { org_id: req.user.org_id } });

    res.json({
      entitlement: state.entitlement,
      active: state.active,
      canResearch: state.canResearch,
      exhausted: state.exhausted,
      reason: state.reason,
      usage: state.usage,
      limits: state.limits,
      settings,
    });
  } catch (error) {
    console.error("Get prospecting summary error:", error);
    return sendErrorResponse(res, 500, "Failed to load AI Prospecting summary.");
  }
};

exports.updateSettings = async (req, res) => {
  try {
    const entitlement = req.prospectingEntitlement;
    const selectedProviders = asArray(req.body.selectedProviders).filter((provider) =>
      asArray(entitlement.supportedProviders).includes(provider)
    );

    const [settings] = await db.prospectingOrgSetting.upsert({
      org_id: req.user.org_id,
      idealCustomerProfile: req.body.idealCustomerProfile || {},
      selectedProviders,
      defaultReviewMode: req.body.defaultReviewMode || "manual",
    });

    await writeAudit({
      req,
      org_id: req.user.org_id,
      action: "prospecting.settings.updated",
      entityType: "prospecting_org_settings",
      entityId: settings?.id || req.user.org_id,
      metadata: { selectedProviders },
    });

    res.json({ message: "AI Prospecting settings saved.", settings: await db.prospectingOrgSetting.findOne({ where: { org_id: req.user.org_id } }) });
  } catch (error) {
    console.error("Update prospecting settings error:", error);
    return sendErrorResponse(res, 500, "Failed to save AI Prospecting settings.");
  }
};

exports.createResearchRequest = async (req, res) => {
  try {
    const state = req.prospectingUsage;
    if (!state.canResearch) return sendErrorResponse(res, 403, "New research is blocked for this organization.");

    const settings = await db.prospectingOrgSetting.findOne({ where: { org_id: req.user.org_id } });
    const providers = asArray(req.body.providers?.length ? req.body.providers : settings?.selectedProviders);
    const approvedProviders = asArray(req.prospectingEntitlement.supportedProviders);
    const allowedProviders = providers.filter((provider) => approvedProviders.includes(provider));
    if (!allowedProviders.length) {
      return sendErrorResponse(res, 400, "Select at least one Super Master-approved provider.");
    }

    const request = await db.prospectingResearchRequest.create({
      org_id: req.user.org_id,
      user_id: req.user.id,
      title: clean(req.body.title) || "Phase 2 Test Research",
      criteria: req.body.criteria || {},
      providers: allowedProviders,
      status: "completed",
      requestedResearchCount: 1,
      completedAt: new Date(),
    });

    const prospectRows = buildTestProspects({
      org_id: req.user.org_id,
      user_id: req.user.id,
      requestId: request.id,
      criteria: req.body.criteria || {},
      providers: allowedProviders,
    });
    const prospects = await db.prospectingProspect.bulkCreate(prospectRows, { returning: true });

    for (const prospect of prospects) {
      await db.prospectingEvidence.bulkCreate([
        {
          org_id: req.user.org_id,
          prospectId: prospect.id,
          evidenceType: "icp_match",
          title: "TEST DATA - ICP fit",
          value: prospect.evidenceSummary,
          confidence: 82,
        },
        {
          org_id: req.user.org_id,
          prospectId: prospect.id,
          evidenceType: "verification",
          title: "TEST DATA - Contact format verification",
          value: "Uses reserved .invalid domain; no live provider was called.",
          confidence: 100,
        },
      ]);
    }

    await request.update({
      verifiedProspectCount: prospects.length,
      providerCreditsUsed: prospects.length,
      aiTokensUsed: 0,
    });
    await writeUsage({ org_id: req.user.org_id, user_id: req.user.id, requestId: request.id, entryType: "research", quantity: 1, reason: "phase2_mock_research" });
    await writeUsage({ org_id: req.user.org_id, user_id: req.user.id, requestId: request.id, entryType: "verified_prospect", quantity: prospects.length, reason: "phase2_mock_verified" });
    await writeUsage({ org_id: req.user.org_id, user_id: req.user.id, requestId: request.id, entryType: "provider_credit", quantity: prospects.length, reason: "phase2_mock_provider_credit" });
    await writeAudit({
      req,
      org_id: req.user.org_id,
      action: "prospecting.research.created",
      entityType: "prospecting_research_request",
      entityId: request.id,
      metadata: { liveProviderIntegrated: false, prospectCount: prospects.length },
    });

    res.status(201).json({ message: "Phase 2 test research created.", request, prospects });
  } catch (error) {
    console.error("Create prospecting research error:", error);
    return sendErrorResponse(res, 500, "Failed to create AI Prospecting research.");
  }
};

